import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '../../..');
const dir = path.join(root, '.server/community-account-20261015');
const copy = (from, to) => { fs.mkdirSync(path.dirname(to), { recursive: true }); fs.cpSync(from, to, { recursive: true }); };
copy(path.join(root, 'apps/api/src/community-prototype'), path.join(dir, 'overlay/apps/api/src/community-prototype'));
copy(path.join(root, 'packages/shared/src/contracts/community-resources.ts'), path.join(dir, 'overlay/packages/shared/src/contracts/community-resources.ts'));
copy(path.join(root, 'prototype/community/public'), path.join(dir, 'overlay/prototype/community/public'));
const baseline = fs.readFileSync(path.join(dir, 'base/api/index.ts'), 'utf8');
const current = fs.readFileSync(path.join(root, 'apps/api/src/index.ts'), 'utf8');
const addition = current.slice(current.indexOf('// Share the existing account/character'), current.indexOf('const server = serve({ fetch: app.fetch'));
if (!addition.includes('issueCommunityHandoff')) throw Error('Missing integration entry');
fs.writeFileSync(path.join(dir, 'overlay/apps/api/src/index.ts'), baseline.replace('const server = serve({ fetch: app.fetch', addition + 'const server = serve({ fetch: app.fetch'));
let phone = fs.readFileSync(path.join(dir, 'base/api/routes/phone.ts'), 'utf8');
phone = "import { communityPhonePersona } from '../community-prototype/phone-persona';\n" + phone;
if (!phone.includes("persona: character.description || ''")) throw Error('Phone baseline changed');
phone = phone.replace("persona: character.description || ''", 'persona: communityPhonePersona(charactersService.getRow(character.id)!)');
fs.mkdirSync(path.join(dir, 'overlay/apps/api/src/routes'), { recursive: true });
fs.writeFileSync(path.join(dir, 'overlay/apps/api/src/routes/phone.ts'), phone);
fs.writeFileSync(path.join(dir, 'Dockerfile'), 'FROM yelan-api:empty-reply-20261013\nCOPY overlay/ /app/\n');
fs.writeFileSync(path.join(dir, '.dockerignore'), '*\n!Dockerfile\n!overlay\n!overlay/**\n');
console.log('Narrow overlay prepared against the deployed API image.');
